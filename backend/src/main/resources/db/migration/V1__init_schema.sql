-- Esquema inicial de FinTrack

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)             NOT NULL,
    email       VARCHAR(150)             NOT NULL,
    password    VARCHAR(255)             NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE categories (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT       NOT NULL,
    name     VARCHAR(60)  NOT NULL,
    type     VARCHAR(10)  NOT NULL,
    color    VARCHAR(7)   NOT NULL,
    icon     VARCHAR(40),
    CONSTRAINT fk_categories_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_categories_user_name_type UNIQUE (user_id, name, type),
    CONSTRAINT ck_categories_type CHECK (type IN ('INCOME', 'EXPENSE'))
);

CREATE TABLE transactions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT                   NOT NULL,
    category_id       BIGINT                   NOT NULL,
    amount            NUMERIC(14, 2)           NOT NULL,
    transaction_date  DATE                     NOT NULL,
    description       VARCHAR(255),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_transactions_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_transactions_amount CHECK (amount > 0)
);

CREATE INDEX idx_transactions_user_date ON transactions (user_id, transaction_date);
CREATE INDEX idx_transactions_category ON transactions (category_id);

CREATE TABLE budgets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT         NOT NULL,
    category_id   BIGINT         NOT NULL,
    budget_year   INTEGER        NOT NULL,
    budget_month  INTEGER        NOT NULL,
    amount_limit  NUMERIC(14, 2) NOT NULL,
    CONSTRAINT fk_budgets_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_budgets_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE CASCADE,
    CONSTRAINT uk_budgets_period UNIQUE (user_id, category_id, budget_year, budget_month),
    CONSTRAINT ck_budgets_month CHECK (budget_month BETWEEN 1 AND 12),
    CONSTRAINT ck_budgets_limit CHECK (amount_limit > 0)
);
